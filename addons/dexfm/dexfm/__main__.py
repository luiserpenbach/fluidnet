"""Single entry point:  python -m dexfm run <config.yaml> [--out DIR] [--start]

Solves the design point, the throttle sweep (with and without the oxygen back-pressure valve),
optionally the experimental lumped start transient, and writes summary JSON, a fluidnet netlist and the HTML report.
Trade-study JSON files found in the output directory (see dexfm.studies) are plotted too.
"""
from __future__ import annotations
import argparse, json
from dataclasses import asdict
from pathlib import Path
from .config import load
from .cycle import solve
from .offdesign import build_pack, throttle_sweep
from .adapters import fluidnet_netlist
from . import report as rp


def main():
    ap = argparse.ArgumentParser(prog="dexfm")
    ap.add_argument("cmd", choices=["run"]); ap.add_argument("config")
    ap.add_argument("--out", default="out"); ap.add_argument("--start", action="store_true", help="also run the experimental lumped start transient")
    a = ap.parse_args()
    out = Path(a.out); out.mkdir(parents=True, exist_ok=True)
    cfg = load(a.config)
    r = solve(cfg)
    s = rp.summary(r)
    (out / f"{cfg.name}_summary.json").write_text(json.dumps(s, indent=1))
    (out / f"{cfg.name}_netlist.json").write_text(json.dumps(fluidnet_netlist(r), indent=1, default=float))
    print(f"{cfg.name} [{cfg.sha()}] closed={r.closed} Pc={cfg.pc / 1e5:.1f} bar Isp={r.setup.isp:.1f} s")
    figs = [rp.fig_chamber(r)]
    if r.closed and r.ox.turbine is not None:
        pm = build_pack(r)
        levels = [1.0, 0.9, 0.8, 0.7, 0.6, 0.5, 0.4, 0.35, 0.3, 0.25, 0.2, 0.15]
        pts = throttle_sweep(pm, levels)
        ptsf = throttle_sweep(pm, [1.0, 0.9, 0.8, 0.7, 0.6, 0.55, 0.5, 0.45, 0.4, 0.35, 0.3], p_floor_ox=55e5)
        (out / f"{cfg.name}_throttle.json").write_text(json.dumps(
            {"free": [asdict(p) if p else None for p in pts], "floor_55bar": [asdict(p) if p else None for p in ptsf]}, indent=1, default=float))
        figs.append(rp.fig_throttle(pts, ptsf))
        if a.start:
            from .transient import simulate_start, StartSpec
            res = simulate_start(pm, StartSpec())
            (out / f"{cfg.name}_start.json").write_text(json.dumps({k: (v.tolist() if hasattr(v, "tolist") else v) for k, v in res.items()}))
            figs.append(rp.fig_start(res, r)); print("start transient ended with:", res["event"])
        try:
            import fluidnet as fnet
            from . import fluidnet_model as fm
            params, err = fm.calibrate(r)
            (out / f"{cfg.name}_fluidnet_calibration.json").write_text(json.dumps({"params": params, "max_residual": err}, indent=1))
            fnet.save(fm.build_model(r, params), str(out / f"{cfg.name}_powerpack_fluidnet.yaml"))
            fnet.save(fm.start_model(r, params, fm.DEFAULT_START), str(out / f"{cfg.name}_start_fluidnet.yaml"))
            res = fm.run_start(r, params)
            figs.append(rp.fig_start_fluidnet(res, r))
            print(f"fluidnet: calibration residual {err:.1e}, start ends at Pc {res.last('tca.Pc') / 1e5:.1f} bar, O/F {res.last('tca.OF'):.2f}")
        except ImportError:
            print("fluidnet not installed: network model and start transient skipped")
    for name, fn in (("arch_sweep.json", rp.fig_arch), ("sensitivity.json", rp.fig_sens)):
        if (out / name).exists():
            figs.append(fn(json.loads((out / name).read_text())))
    rp.write_html(figs, out / f"{cfg.name}_report.html", f"{cfg.name} dual expander engine: toolchain report",
                  f"Configuration hash {cfg.sha()}. Generated by dexfm; every number traces to the YAML configuration.")


if __name__ == "__main__":
    main()
