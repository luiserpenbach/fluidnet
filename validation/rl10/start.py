"""RL10A-3-3A start transient: time to accelerate (MES to Pc = 200 psia).

Builds the start model from the calibrated steady model (examples/rl10a33a.yaml)
following the start description in NASA TM-107318 sec. 2.1 and CR-195478:

- before MES the fuel pump is chilled and the cooldown valves vent overboard;
  FSOV closed; jacket metal and the gas in it at 540 R, jacket inlet manifold
  at 200 R; the LOX pump is chilled by OCV bleed flow vented through the chamber;
- at MES (t = 0) the FSOV opens and the discharge cooldown valve FCV2 closes;
  the interstage cooldown valve FCV1 stays partly open;
- spark ignition at 0.3 s (first burn);
- the OCV main orifice opens on LOX pump pressure rise and FCV1 closes on fuel
  pump discharge pressure (pneumatic, one-shot);
- the TCV opens with chamber pressure (Binder: linear in Pc) with a lag; it is
  half open at about the TP1 chamber pressure, as in the steady model.

Valve set points are not published; the nominal values below are assumptions
and the sensitivity runs vary them over the range Binder examined.
Writes examples/rl10a33a_start.yaml and start_results.json.
"""
from __future__ import annotations

import copy
import json
import sys
import time
from pathlib import Path

import numpy as np

import fluidnet as fn

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
PSI = 6894.757293
RANK = 5.0 / 9.0

# time to accelerate, CR-195478 Table 2 (s from MES): (run, ROCETS simulated, measured)
TTA_TABLE = [
    ("ground test", 2.09, 2.26),
    ("ground test", 1.80, 1.90),
    ("ground test", 1.51, 1.43),
    ("ground test", 1.72, 1.70),
    ("ground test, second burn", 1.91, 1.84),
    ("ground test, second burn", 2.00, 2.08),
    ("flight", 1.98, 1.90),
    ("flight", 1.95, 1.67),
    ("not legible", 2.33, 2.56),
]

NOMINAL = {
    "ignition": 0.3,  # s after MES
    "ocv_dp": 100.0,  # psid, LOX pump rise that opens the OCV (Binder ran 50-150)
    "fcv1_p": 250.0,  # psia, fuel pump discharge that closes FCV1
    "jacket_T": 540.0,  # R
    "tcv_pc": (442.35, 502.35),  # psia, TCV closed .. fully open (half open, as in the steady model, at the TP1 chamber pressure)
    "fcv1_open": 0.3,  # partial opening of FCV1 at MES
    "jacket_P": 2.0,  # psia, jacket side before MES (vented overboard)
    "bleed_cd": 0.25,  # OCV start bleed: effective area 0.25 x 0.615 in2
}


def comp(m, cid):
    for c in m["components"]:
        if c["id"] == cid:
            return c
    raise KeyError(cid)


def start_model(p: dict) -> dict:
    m = fn.load(ROOT / "examples" / "rl10a33a.yaml")
    m["name"] = "RL10A-3-3A start"
    m["description"] = (
        "Ground-test start of the RL10A-3-3A from the calibrated steady model: "
        "chilled pumps at rest, warm jacket (540 R), FSOV opening at MES, spark at 0.3 s, "
        "OCV and FCV1 sequenced by pump pressures, TCV opening with chamber pressure. "
        "Generated by validation/rl10/start.py."
    )
    warm = f"{p['jacket_T']:g} degR"
    # fuel feed and pumps chilled, at tank pressure
    for cid in ("fuel_inlet", "interstage", "fuel_pump_discharge", "fuel_duct"):
        c = comp(m, cid)
        c["P0"], c["T0"] = "27 psi", "21.5 K"
    c = comp(m, "jacket_inlet")
    c["P0"], c["T0"] = f"{p['jacket_P']:g} psi", "200 degR"
    # before MES the discharge cooldown valve vents the jacket side overboard
    for cid in ("jacket_down", "jacket_turn", "jacket_up_nozzle", "jacket_up_chamber", "venturi_inlet",
                "turbine_inlet", "turbine_exit", "turbine_duct"):
        c = comp(m, cid)
        c["P0"], c["T0"] = f"{p['jacket_P']:g} psi", warm
        if "wall_T0" in c:
            c["wall_T0"] = warm
    c = comp(m, "fuel_manifold")
    c["P0"], c["T0"] = "1 psi", warm
    # LOX side chilled up to the OCV; plenum holds cold vapour at chamber pressure
    for cid in ("lox_inlet", "lox_discharge", "lox_duct", "ocv_inlet"):
        c = comp(m, cid)
        c["P0"], c["T0"] = "35.8 psi", "97.06 K"
    c = comp(m, "lox_plenum")
    c["P0"], c["T0"] = "1 psi", "100 K"
    comp(m, "turbopump")["N0"] = "0 rpm"
    tca = comp(m, "tca")
    tca["P0"] = "1 psi"
    tca["ignition_time"] = f"{p['ignition']:g} s"
    # valves
    comp(m, "fsov")["opening"] = [[0, 0], [0.05, 1]]
    comp(m, "fcv2")["opening"] = 0
    fcv1 = comp(m, "fcv1")
    fcv1.update({"opening": p["fcv1_open"], "sense": "fuel_pump_discharge", "sense_lo": f"{p['fcv1_p']:g} psi",
                 "sense_hi": f"{p['fcv1_p'] + 20:g} psi", "opening_lo": p["fcv1_open"], "opening_hi": 0,
                 "actuator_time": "50 ms", "latch": True})
    ocv = comp(m, "ocv")
    ocv.update({"opening": 0, "sense": "lox_discharge", "sense_ref": "lox_pump.in", "sense_lo": f"{p['ocv_dp']:g} psi",
                "sense_hi": f"{p['ocv_dp'] + 10:g} psi", "opening_lo": 0, "opening_hi": 1, "actuator_time": "50 ms",
                "latch": True})
    comp(m, "ocv_bleed")["cd"] = p["bleed_cd"]
    tcv = comp(m, "tcv")
    lo, hi = p["tcv_pc"]
    tcv.update({"opening": 0, "sense": "tca", "sense_lo": f"{lo:g} psi", "sense_hi": f"{hi:g} psi", "opening_lo": 0,
                "opening_hi": 1, "actuator_time": "150 ms"})
    # steady_time: a steady-state solve of this model evaluates the schedules after the start
    m["simulation"] = {"t_end": 4.0, "output_dt": 0.005, "rtol": 1e-4, "max_step": 0.01, "steady_time": 4.0}
    return m


def time_to(res, ch, level):
    t, y = res.time, res[ch]
    i = np.argmax(y >= level)
    if y[i] < level:
        return float("nan")
    if i == 0:
        return float(t[0])
    return float(t[i - 1] + (level - y[i - 1]) * (t[i] - t[i - 1]) / (y[i] - y[i - 1]))


def run(p: dict) -> dict:
    m = start_model(p)
    t0 = time.perf_counter()
    r = fn.run(m)
    el = time.perf_counter() - t0
    out = {
        "params": p,
        "elapsed_s": el,
        "error": r.error,
        "tta": time_to(r, "tca.Pc", 200 * PSI),
        "t90": time_to(r, "tca.thrust", 0.9 * 73854.0),
        "final": {"Pc": r.last("tca.Pc") / PSI, "thrust": r.last("tca.thrust") / 4.4482216, "OF": r.last("tca.OF"),
                  "speed": r.last("turbopump.speed") * 60 / 2 / np.pi},
    }
    out["ocv_open_t"] = time_to(r, "ocv.opening", 0.5)
    return out, r


def main():
    t0 = time.time()
    nominal_out, r = run(dict(NOMINAL))
    m = start_model(dict(NOMINAL))
    fn.save(m, ROOT / "examples" / "rl10a33a_start.yaml")
    print(f"nominal: time to accelerate {nominal_out['tta']:.3f} s, 90 % thrust {nominal_out['t90']:.3f} s, "
          f"run {nominal_out['elapsed_s']:.1f} s, error {nominal_out['error']}")
    print("  final", nominal_out["final"])
    # time histories for the report
    keep = ["tca.Pc", "tca.thrust", "turbopump.speed", "tca.OF", "turbine_inlet.T", "fuel_pump_discharge.P",
            "lox_discharge.P", "ocv.opening", "fcv1.opening", "tcv.opening", "jacket_up_chamber.Tw_max",
            "fuel_pump_1.mdot", "lox_pump.mdot", "turbine_inlet.P", "fuel_pump_1.in.x"]
    hist = {"time": r.time.tolist()}
    for k in keep:
        if k in r:
            hist[k] = r[k].tolist()
    sens = []
    variants = [
        ("bleed_cd", 0.15), ("bleed_cd", 0.35),
        ("fcv1_open", 0.2), ("fcv1_open", 0.5),
        ("ocv_dp", 50.0), ("ocv_dp", 150.0),
        ("ignition", 0.1), ("ignition", 0.4),
        ("fcv1_p", 150.0), ("fcv1_p", 400.0),
        ("jacket_T", 350.0),
        ("tcv_pc", (412.35, 532.35)),
    ]
    for key, val in variants:
        p = dict(NOMINAL)
        p[key] = val
        o, _ = run(p)
        sens.append({"param": key, "value": val, "tta": o["tta"], "t90": o["t90"], "error": o["error"], "final": o["final"]})
        print(f"  {key} = {val}: time to accelerate {o['tta']:.3f} s  (error {o['error']})")
    (HERE / "start_results.json").write_text(json.dumps({"nominal": nominal_out, "sensitivity": sens, "history": hist,
                                                         "table": TTA_TABLE}, indent=1))
    print(f"done in {time.time() - t0:.1f} s")


if __name__ == "__main__":
    main()
