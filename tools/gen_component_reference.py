"""Generate docs/03-user-guide/component-reference.md from the component catalog.

The catalog in crates/fluidnet-core/src/catalog.rs is the single source of truth
for component types, ports, parameters, units and defaults. This script reads it
through `fluidnet catalog` (the CLI) or, if no CLI binary is found, through the
Python package, and writes the reference page.

Usage:  python tools/gen_component_reference.py [--cli PATH] [--out FILE]
"""
from __future__ import annotations

import argparse
import json
import shutil
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "03-user-guide" / "component-reference.md"

# Revision table of the generated page. Add a row when the catalog changes in
# substance; the page header takes the last row. A fixed date keeps the output
# reproducible, so CI can check that the committed page is up to date.
REVISIONS = [
    ("A", "2026-11-02", "First release, generated from the v0.5.0 catalog"),
]

CATEGORY_ORDER = ["Boundaries", "Volumes", "Lines", "Restrictions", "Machines", "Engine"]


def load_catalog(cli: str | None) -> dict:
    cands = [cli] if cli else [
        str(ROOT / "target" / "release" / "fluidnet"),
        str(ROOT / "target" / "release" / "fluidnet.exe"),
        shutil.which("fluidnet"),
    ]
    for c in cands:
        if c and Path(c).exists():
            return json.loads(subprocess.run([c, "catalog"], capture_output=True, text=True, check=True).stdout)
    import fluidnet  # noqa: PLC0415  (fallback: Python package)

    return fluidnet.catalog()


def cell(s: str) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ")


def default_text(p: dict) -> str:
    d = p.get("default")
    if d is None or d == "":
        return "required" if p.get("required") else "–"
    if p.get("si") not in (None, "", "-") and p["kind"] == "quantity":
        try:
            float(d)
        except (TypeError, ValueError):
            return str(d)  # already carries a unit, e.g. "1.5 um"
        return f"{d} {p['si']}"
    return str(d)


def unit_text(p: dict) -> str:
    if p["kind"] == "choice":
        return "one of " + ", ".join(f"`{c}`" for c in p["choices"])
    if p["kind"] == "ref":
        return f"id of a `{p['target']}`"
    if p["kind"] == "fluid":
        return "fluid key"
    if p["kind"] == "int":
        return "integer"
    if p["kind"] == "bool":
        return "true / false"
    if p["kind"] == "text":
        return "text"
    si, ui = p.get("si", "-"), p.get("unit", "-")
    if si in ("", "-"):
        return "–" if ui in ("", "-") else ui
    return si if ui in ("", "-", si) else f"{si} (UI: {ui})"


def render(cat: dict) -> str:
    comps = cat["components"]
    by_cat: dict[str, list] = {}
    for c in comps:
        by_cat.setdefault(c["category"], []).append(c)
    order = [k for k in CATEGORY_ORDER if k in by_cat] + sorted(k for k in by_cat if k not in CATEGORY_ORDER)

    out = [
        "# Component reference",
        "",
        f"FNT-CMP-HBK-001 · Rev {REVISIONS[-1][0]} · Released · {REVISIONS[-1][1]} · Owner: Luis Erpenbach",
        "",
        "> Generated by `tools/gen_component_reference.py` from the component catalog",
        "> (`crates/fluidnet-core/src/catalog.rs`, printed by `fluidnet catalog`). Do not",
        "> edit this page by hand: change the catalog and regenerate.",
        "",
        "Every component in a model file has an `id`, a `type` from this page and the",
        "parameters listed for that type. Quantities accept a unit string (`25 bar`,",
        "`6 mm`, `0.5 lb/s`); bare numbers are SI, in the unit given in the SI column.",
        "Parameters marked schedulable also accept a table `[[t, value], ...]`,",
        "interpolated linearly in time. The equations behind each type are in the",
        "engineering section; the output channels each type produces are listed in",
        "[Output channels and result files](outputs.md). The model file format itself is",
        "in the [model file standard](model-files.md).",
        "",
        "## Overview",
        "",
        "| Type | Category | Ports | Description |",
        "|---|---|---|---|",
    ]
    for k in order:
        for c in by_cat[k]:
            ports = ", ".join(f"`{p}`" for p in c["ports"]) or "none"
            out.append(f"| [`{c['type']}`](#{c['type']}) | {k} | {ports} | {cell(c['label'])} |")
    out.append("")
    out.append("Columns of the parameter tables: **Unit** is the SI unit a bare number is read")
    out.append("in (and the display unit the web UI uses, if different); **Default** is the value")
    out.append("used when the parameter is omitted (\"required\" if it must be given, \"–\" if the")
    out.append("parameter is optional and has no default); **Sched.** marks parameters that")
    out.append("accept a time table.")
    out.append("")
    for k in order:
        out.append(f"## {k}")
        out.append("")
        for c in by_cat[k]:
            out.append(f"### {c['type']}")
            out.append("")
            out.append(f"**{c['label']}.** {c['help']}")
            out.append("")
            ports = ", ".join(f"`{p}`" for p in c["ports"]) or "none (not connected by ports)"
            kind = "node (its port joins the node it is connected to)" if c.get("node_like") else "branch or standalone element"
            out.append(f"Ports: {ports}. Network role: {kind}.")
            out.append("")
            out.append("| Key | Label | Unit | Default | Sched. | Description |")
            out.append("|---|---|---|---|---|---|")
            for p in c["params"]:
                out.append(
                    f"| `{p['key']}` | {cell(p['label'])} | {cell(unit_text(p))} | {cell(default_text(p))} | "
                    f"{'yes' if p.get('schedulable') else ''} | {cell(p['help'])} |"
                )
            out.append("")
    out += [
        "## Revision history",
        "",
        "| Rev | Date | Change |",
        "|---|---|---|",
        *[f"| {r} | {d} | {c} |" for r, d, c in REVISIONS],
        "",
    ]
    return "\n".join(out)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--cli", help="path to the fluidnet CLI binary")
    ap.add_argument("--out", default=str(OUT))
    a = ap.parse_args()
    text = render(load_catalog(a.cli))
    Path(a.out).write_text(text, encoding="utf-8")
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
